package composedeploy

import (
	"context"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/deranjer/vigara/internal/stack"
)

var errRecovery = errors.New("standalone recovery files could not be prepared; check the stack directory on this device")

const recoveryDirectory = ".vigara-recovery"
const recoveryHeader = "#!/bin/sh\n# Generated by Vigara. Starts this deployed stack without Vigara or Git.\n"

// These names belong to the deployment runner, never to repository inputs.
func validateRecoveryPaths(s stack.Snapshot, m stack.Manifest) error {
	reserved := func(p string) bool {
		first := strings.SplitN(p, "/", 2)[0]
		return first == recoveryDirectory || first == "start.sh"
	}
	for p := range s.Files {
		if reserved(p) {
			return errRecovery
		}
	}
	for _, input := range m.Compose.EnvironmentFiles {
		if reserved(input.Target) {
			return errRecovery
		}
	}
	return nil
}

func shellQuote(value string) string {
	return "'" + strings.ReplaceAll(value, "'", "'\"'\"'") + "'"
}

func checkRecoveryTarget(t Target) error {
	for _, p := range []string{recoveryDirectory, "start.sh"} {
		info, err := os.Lstat(filepath.Join(t.Directory, p))
		if err != nil && !os.IsNotExist(err) {
			return errRecovery
		}
		if err == nil && (info.Mode()&os.ModeSymlink != 0 || (p == recoveryDirectory && !info.IsDir()) || (p == "start.sh" && !info.Mode().IsRegular())) {
			return errRecovery
		}
		if err == nil && p == "start.sh" {
			data, err := os.ReadFile(filepath.Join(t.Directory, p))
			if err != nil || !strings.HasPrefix(string(data), recoveryHeader) {
				return errRecovery
			}
		}
	}
	return nil
}

// recovery persists the exact interpolation inputs used by this deployment.
// Publish the launcher only after validating the complete on-disk invocation.
// Both managed deployment and manual recovery then use the same durable files.
func (r *Runner) recovery(ctx context.Context, t Target, m stack.Manifest, workspace, override string) ([]string, error) {
	if err := checkRecoveryTarget(t); err != nil {
		return nil, err
	}
	root := filepath.Join(t.Directory, recoveryDirectory)
	if os.MkdirAll(root, 0700) != nil || os.Chmod(root, 0700) != nil {
		return nil, errRecovery
	}
	bundle, err := os.MkdirTemp(root, "release-")
	if err != nil {
		return nil, errRecovery
	}
	published := false
	defer func() {
		if !published {
			os.RemoveAll(bundle)
		}
	}()
	// A host project may itself be a Git checkout. Never let a routine git add
	// pick up these plaintext runtime inputs, including this ignore file itself.
	if os.WriteFile(filepath.Join(bundle, ".gitignore"), []byte("*\n"), 0600) != nil {
		return nil, errRecovery
	}
	args := []string{"compose", "-p", m.ProjectName, "--project-directory", t.Directory}
	for _, p := range m.Compose.Files {
		args = append(args, "-f", filepath.Join(t.Directory, filepath.FromSlash(p)))
	}
	for i := range m.Compose.InterpolationFiles {
		name := fmt.Sprintf("input-%d.env", i)
		plain, err := os.ReadFile(filepath.Join(workspace, fmt.Sprintf(".vigara-input-%d", i)))
		if err != nil || os.WriteFile(filepath.Join(bundle, name), plain, 0600) != nil {
			return nil, errRecovery
		}
		args = append(args, "--env-file", filepath.Join(bundle, name))
	}
	args = append(args, "-f", override)
	if _, err := r.command(ctx, t.Directory, append(args, "config", "--quiet")...); err != nil {
		return nil, errCompose
	}

	var script strings.Builder
	script.WriteString(recoveryHeader + "set -eu\n")
	script.WriteString("stack_dir=$(CDPATH= cd -- \"$(dirname -- \"$0\")\" && pwd -P)\ncd -- \"$stack_dir\"\n")
	// Match command's isolated environment. In particular, caller passwords,
	// COMPOSE_FILE and COMPOSE_PROFILES must not override the saved deployment.
	script.WriteString("exec env -i PATH=\"$PATH\" HOME=\"${HOME:-}\" ")
	script.WriteString(shellQuote("DOCKER_HOST=" + r.DockerHost))
	script.WriteString(" COMPOSE_DISABLE_ENV_FILE=1 COMPOSE_ANSI=never COMPOSE_PROGRESS=plain docker")
	for _, arg := range args {
		script.WriteByte(' ')
		if arg == t.Directory {
			script.WriteString("\"$stack_dir\"")
		} else if filepath.IsAbs(arg) && strings.HasPrefix(arg, t.Directory+string(filepath.Separator)) {
			rel, err := filepath.Rel(t.Directory, arg)
			if err != nil {
				return nil, errRecovery
			}
			script.WriteString("\"$stack_dir\"/" + shellQuote(filepath.ToSlash(rel)))
		} else {
			script.WriteString(shellQuote(arg))
		}
	}
	script.WriteString(" up --detach --no-build --pull never\n")
	temp, err := os.CreateTemp(t.Directory, ".vigara-start-")
	if err != nil {
		return nil, errRecovery
	}
	defer os.Remove(temp.Name())
	_, writeErr := temp.WriteString(script.String())
	modeErr := temp.Chmod(0700)
	syncErr := temp.Sync()
	closeErr := temp.Close()
	if writeErr != nil || modeErr != nil || syncErr != nil || closeErr != nil || os.Rename(temp.Name(), filepath.Join(t.Directory, "start.sh")) != nil {
		return nil, errRecovery
	}
	published = true
	// Only the current launcher needs plaintext interpolation inputs. Remove old
	// runner-created bundles after publication, never before the new one is ready.
	entries, _ := os.ReadDir(root)
	for _, entry := range entries {
		if entry.IsDir() && entry.Name() != filepath.Base(bundle) && strings.HasPrefix(entry.Name(), "release-") && allDigits(strings.TrimPrefix(entry.Name(), "release-")) {
			os.RemoveAll(filepath.Join(root, entry.Name()))
		}
	}
	return args, nil
}

func allDigits(s string) bool {
	if s == "" {
		return false
	}
	for _, c := range s {
		if c < '0' || c > '9' {
			return false
		}
	}
	return true
}
